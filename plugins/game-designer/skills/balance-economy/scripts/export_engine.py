#!/usr/bin/env python3
"""Export a design table (CSV or JSON) into engine-ready data and code.

  python3 export_engine.py cards.csv --name Card --engine all --out build/
  python3 export_engine.py towers.json --name Tower --engine godot --out game/data

Engines:
  godot   card_def.gd (Resource class), cards.json, card_db.gd (loader returning typed rows)
  unity   CardRow.cs (Serializable row), CardTable.cs (ScriptableObject with a JSON loader), cards.json
  unreal  CardRow.h (USTRUCT : FTableRowBase), cards_datatable.csv (first column "Name" for import)
  json    cards.json only (typed values, provenance in "_source")
  all     every engine above, each in its own subfolder

Input: a CSV with a header row (lines starting with # are skipped), a JSON list of objects, or
a JSON object holding a list (pick it with --key when there are several). Column types are inferred per column:
int, float, bool (true/false/yes/no) or string. Every generated file names its source so the
numbers keep their provenance. Standard library only; no network access.
"""
from __future__ import annotations

import argparse
import csv
import datetime as _dt
import json
import os
import re
import sys

BOOL_T, BOOL_F = {"true", "yes"}, {"false", "no"}


def read_rows(path: str, key: str | None = None) -> list[dict]:
    if path.lower().endswith(".json"):
        data = json.load(open(path, encoding="utf-8"))
        if isinstance(data, dict):
            if key:
                if not isinstance(data.get(key), list):
                    raise SystemExit(f"error: no list named {key!r}; lists here: {[k for k, v in data.items() if isinstance(v, list)]}")
                data = data[key]
            else:
                lists = {k: v for k, v in data.items() if isinstance(v, list)}
                if len(lists) != 1:
                    raise SystemExit(f"error: the JSON object holds {len(lists)} lists ({', '.join(lists)}); pick one with --key")
                data = next(iter(lists.values()))
        if not isinstance(data, list) or not all(isinstance(r, dict) for r in data):
            raise SystemExit("error: JSON input must be a list of objects")
        return [{k: ("" if v is None else v) for k, v in r.items()} for r in data]
    with open(path, encoding="utf-8", newline="") as f:
        lines = [ln for ln in f if ln.strip() and not ln.lstrip().startswith("#")]
    return list(csv.DictReader(lines))


def infer(values: list) -> str:
    vals = [v for v in values if v != ""]
    if not vals:
        return "string"
    if all(isinstance(v, bool) or str(v).strip().lower() in BOOL_T | BOOL_F for v in vals):
        return "bool"
    def is_int(v):
        if isinstance(v, bool):
            return False
        try:
            return float(str(v)) == int(float(str(v))) and "." not in str(v) and "e" not in str(v).lower()
        except ValueError:
            return False
    def is_num(v):
        try:
            float(str(v)); return not isinstance(v, bool)
        except ValueError:
            return False
    if all(is_int(v) for v in vals):
        return "int"
    if all(is_num(v) for v in vals):
        return "float"
    return "string"


def cast(v, t: str):
    if t == "int":
        return int(float(v)) if v != "" else 0
    if t == "float":
        return float(v) if v != "" else 0.0
    if t == "bool":
        return v if isinstance(v, bool) else str(v).strip().lower() in BOOL_T
    return "" if v is None else str(v)


def words(name: str) -> list[str]:
    parts = re.findall(r"[A-Za-z][a-z0-9]*|[A-Z]+(?![a-z])|\d+", re.sub(r"[^A-Za-z0-9]+", " ", name))
    return [p.lower() for p in parts] or ["field"]


def snake(name: str) -> str:
    s = "_".join(words(name)); return s if not s[0].isdigit() else "f_" + s


def camel(name: str) -> str:
    w = words(name); s = w[0] + "".join(x.capitalize() for x in w[1:]); return s if not s[0].isdigit() else "f" + s


def pascal(name: str) -> str:
    s = "".join(x.capitalize() for x in words(name)); return s if not s[0].isdigit() else "F" + s


def header(comment: str, source: str) -> str:
    stamp = _dt.date.today().isoformat()
    return f"{comment} Generated by ai-game-designer export_engine.py on {stamp}.\n{comment} Source: {source}. Edit the source table and re-export instead of editing this file.\n"


def write(path: str, text: str) -> str:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return path


def export_json(rows, schema, name, source, out) -> list[str]:
    data = {"_source": source, "rows": [{k: cast(r.get(k, ""), t) for k, t in schema} for r in rows]}
    return [write(os.path.join(out, f"{snake(name)}s.json"), json.dumps(data, indent=2, ensure_ascii=False) + "\n")]


def export_godot(rows, schema, name, source, out) -> list[str]:
    gd_t = {"int": "int", "float": "float", "bool": "bool", "string": "String"}
    cls, base = pascal(name) + "Def", snake(name)
    fields = "".join(f"@export var {snake(k)}: {gd_t[t]}\n" for k, t in schema)
    assign = "".join(f"\t\trow.{snake(k)} = {gd_t[t]}(item.get(\"{k}\", {repr_default(t)}))\n" if t != "string"
                     else f"\t\trow.{snake(k)} = str(item.get(\"{k}\", \"\"))\n" for k, t in schema)
    files = export_json(rows, schema, name, source, out)
    files.append(write(os.path.join(out, f"{base}_def.gd"), header("#", source) +
        f"class_name {cls}\nextends Resource\n\n{fields}"))
    files.append(write(os.path.join(out, f"{base}_db.gd"), header("#", source) +
        f"class_name {pascal(name)}Db\nextends RefCounted\n\n"
        f"## Loads {base}s.json into typed {cls} rows.\n"
        f"static func load_rows(path: String = \"res://data/{base}s.json\") -> Array[{cls}]:\n"
        f"\tvar rows: Array[{cls}] = []\n"
        f"\tvar parsed = JSON.parse_string(FileAccess.get_file_as_string(path))\n"
        f"\tif parsed == null:\n\t\tpush_error(\"Could not parse %s\" % path)\n\t\treturn rows\n"
        f"\tfor item in parsed[\"rows\"]:\n\t\tvar row := {cls}.new()\n{assign}\t\trows.append(row)\n\treturn rows\n"))
    return files


def repr_default(t: str) -> str:
    return {"int": "0", "float": "0.0", "bool": "false"}[t]


def export_unity(rows, schema, name, source, out) -> list[str]:
    cs_t = {"int": "int", "float": "float", "bool": "bool", "string": "string"}
    row, table = pascal(name) + "Row", pascal(name) + "Table"
    fields = "".join(f"    public {cs_t[t]} {camel(k)};\n" for k, t in schema)
    # Unity's JsonUtility maps by field name, so the JSON for Unity uses the C# field names.
    data = {"rows": [{camel(k): cast(r.get(k, ""), t) for k, t in schema} for r in rows]}
    files = [write(os.path.join(out, f"{snake(name)}s.json"), json.dumps(data, indent=2, ensure_ascii=False) + "\n")]
    files.append(write(os.path.join(out, f"{row}.cs"), header("//", source) +
        f"using System;\n\n[Serializable]\npublic class {row}\n{{\n{fields}}}\n"))
    files.append(write(os.path.join(out, f"{table}.cs"), header("//", source) +
        "using System.Collections.Generic;\nusing UnityEngine;\n\n"
        f"[CreateAssetMenu(fileName = \"{table}\", menuName = \"Design Data/{table}\")]\n"
        f"public class {table} : ScriptableObject\n{{\n    public List<{row}> rows = new List<{row}>();\n\n"
        f"    [System.Serializable] private class Wrapper {{ public List<{row}> rows; }}\n\n"
        f"    /// <summary>Replace the rows with the contents of {snake(name)}s.json (a TextAsset).</summary>\n"
        f"    public void LoadFromJson(TextAsset json)\n    {{\n        rows = JsonUtility.FromJson<Wrapper>(json.text).rows;\n    }}\n}}\n"))
    return files


def export_unreal(rows, schema, name, source, out) -> list[str]:
    ue_t = {"int": "int32", "float": "float", "bool": "bool", "string": "FString"}
    struct = "F" + pascal(name) + "Row"
    ue = lambda k: "DisplayName" if pascal(k) == "Name" else pascal(k)   # "Name" is the DataTable row key
    key = next((k for k, _ in schema if k.lower() in ("id", "name", "key")), schema[0][0])
    props = "".join(f"    UPROPERTY(EditAnywhere, BlueprintReadOnly, Category = \"Design\")\n    {ue_t[t]} {ue(k)}{' = 0' if t == 'int' else ' = 0.f' if t == 'float' else ' = false' if t == 'bool' else ''};\n\n" for k, t in schema)
    files = [write(os.path.join(out, f"{pascal(name)}Row.h"), header("//", source) +
        "#pragma once\n\n#include \"CoreMinimal.h\"\n#include \"Engine/DataTable.h\"\n"
        f"#include \"{pascal(name)}Row.generated.h\"\n\n"
        f"USTRUCT(BlueprintType)\nstruct {struct} : public FTableRowBase\n{{\n    GENERATED_BODY()\n\n{props.rstrip()}\n}};\n")]
    buf = os.path.join(out, f"{snake(name)}s_datatable.csv")
    os.makedirs(out, exist_ok=True)
    with open(buf, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Name"] + [ue(k) for k, _ in schema])
        seen = set()
        for i, r in enumerate(rows):
            rid = re.sub(r"[^A-Za-z0-9_]", "_", str(r.get(key, "")).strip()) or f"Row_{i + 1}"
            while rid in seen:
                rid += "_"
            seen.add(rid)
            vals = [cast(r.get(k, ""), t) for k, t in schema]
            w.writerow([rid] + [("True" if v else "False") if isinstance(v, bool) else v for v in vals])
    files.append(buf)
    return files


EXPORTERS = {"json": export_json, "godot": export_godot, "unity": export_unity, "unreal": export_unreal}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("table", help="CSV or JSON design table")
    ap.add_argument("--name", required=True, help="singular row name, e.g. Card, Tower, Level")
    ap.add_argument("--engine", choices=list(EXPORTERS) + ["all"], default="all")
    ap.add_argument("--out", default="export", help="output folder")
    ap.add_argument("--key", help="for a JSON object holding several lists, the list to export")
    a = ap.parse_args()
    rows = read_rows(a.table, a.key)
    if not rows:
        print("error: no rows found", file=sys.stderr)
        return 2
    keys = list(dict.fromkeys(k for r in rows for k in r))
    schema = [(k, infer([r.get(k, "") for r in rows])) for k in keys]
    source = os.path.basename(a.table)
    engines = list(EXPORTERS) if a.engine == "all" else [a.engine]
    print(f"{len(rows)} rows · " + ", ".join(f"{k}:{t}" for k, t in schema))
    for e in engines:
        out = os.path.join(a.out, e) if a.engine == "all" else a.out
        for f in EXPORTERS[e](rows, schema, a.name, source, out):
            print(f"  {e:6} {f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
